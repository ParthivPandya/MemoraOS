"""Render benchmark_results.json as Markdown. Every number in the output comes from the JSON."""

from __future__ import annotations

SYSTEM_ORDER = ["bm25", "vector", "hybrid_rag", "hybrid_rag_top1", "hybrid_rag_gated", "memoraos_hybrid_only", "memoraos"]


def _pct(x: float | None) -> str:
    return "–" if x is None else f"{100 * x:.1f}%"


def _order(names: list[str]) -> list[str]:
    return sorted(names, key=lambda n: SYSTEM_ORDER.index(n) if n in SYSTEM_ORDER else 99)


def _table(headers: list[str], rows: list[list[str]]) -> str:
    out = ["| " + " | ".join(headers) + " |", "|" + "|".join("---" for _ in headers) + "|"]
    out += ["| " + " | ".join(r) + " |" for r in rows]
    return "\n".join(out)


def render_markdown(rep: dict) -> str:
    m = rep["metrics"]
    systems = _order(list(m))
    scen = list(next(iter(m.values()))["scenarios"])
    env, cfg = rep["environment"], rep["configuration"]
    L: list[str] = []
    L.append("# MemoraOS Memory Benchmark Report\n")
    L.append("_Generated by `python -m benchmarks.run`. Every figure below is computed from `benchmark_results.json`; nothing is hand-edited._\n")
    L.append("## Conditions\n")
    L.append(f"- Command: `{rep['command']}`")
    L.append(f"- Seeds: {cfg['seeds']} (scale {cfg['scale']}), about {cfg['questions_per_seed_approx']} questions per seed; outcomes are pooled across seeds")
    L.append(f"- Hardware: {env['platform']}, {env['processor']}, {env['cpu_count']} logical CPUs, RAM {env.get('ram_gb')} GB; Python {env['python']}, NumPy {env['numpy']}, SQLite {env['sqlite']}")
    L.append(f"- Embedder for every system: {cfg['embedder']}. No LLM is used by any system or judge; answers are extractive and scoring is mechanical (string containment and ID matching).")
    L.append(f"- Top-k: {cfg['top_k']}. Confidence intervals: 95% bootstrap ({cfg['bootstrap_resamples']} resamples) over questions.")
    L.append("- Dataset SHA-256 per seed: " + ", ".join(f"{k}: `{v[:12]}…`" for k, v in cfg["dataset_sha256"].items()))
    L.append(f"- Deterministic result digest (timing excluded): `{rep['deterministic_digest'][:16]}`")
    L.append(f"- Wall clock: {rep['wall_clock_seconds']} s\n")
    L.append("## Systems\n")
    for s in rep["systems"]:
        L.append(f"- **{s['name']}**: {s['description']}")
    L.append("")

    L.append("## Overall accuracy\n")
    has_split = all("pooled_accuracy_v02_scenarios" in m[s] and "pooled_accuracy_v01_suite" in m[s] for s in systems)

    def ci(s: str, key: str) -> str:
        lo, hi = m[s][f"{key}_ci95"]
        return f"{_pct(m[s][key])} [{_pct(lo)}, {_pct(hi)}]"

    headers = ["System", "Macro accuracy (mean over scenarios)", "Pooled accuracy [95% CI]"]
    if has_split:
        headers += ["v0.1 suite (16 scenarios) [95% CI]", "v0.2 scenarios (3) [95% CI]"]
    rows = []
    for s in systems:
        row = [f"**{s}**" if s == "memoraos" else s, _pct(m[s]["macro_accuracy"]), ci(s, "pooled_accuracy")]
        if has_split:
            row += [ci(s, "pooled_accuracy_v01_suite"), ci(s, "pooled_accuracy_v02_scenarios")]
        rows.append(row)
    L.append(_table(headers, rows))
    if has_split:
        L.append("\nThe 16 v0.1 scenarios keep their original definitions so their headline stays comparable across releases; the 3 scenarios added in v0.2 (`value_normalization`, `negation_and_correction`, `evidence_fusion`) are reported separately and are also included in the pooled figure.")
    L.append("")
    L.append("## Accuracy by scenario\n")
    L.append(_table(["Scenario (n per seed set)"] + systems, [[f"{sc} ({m[systems[0]]['scenarios'][sc]['n']})"] + [_pct(m[s]["scenarios"][sc]["accuracy"]) for s in systems] for sc in scen]))
    L.append("\nScenario-specific correctness: `single/multi/long_*`: gold value(s) present and no stale value present; `contradiction_resolution`: conflicts must be flagged, version updates must resolve to the latest value; `historical_reconstruction` and `unsupported_answers`: abstaining is correct for unanswerable questions.\n")

    def metric_table(title: str, key: str, scenarios: list[str] | None = None) -> None:
        rows = []
        for sc in scenarios or scen:
            vals = [m[s]["scenarios"][sc].get(key) for s in systems]
            if any(v is not None for v in vals):
                rows.append([sc] + [_pct(v) for v in vals])
        if rows:
            L.append(f"## {title}\n")
            L.append(_table(["Scenario"] + systems, rows))
            L.append("")

    metric_table("Unsupported-answer rate (lower is better; unanswerable questions only)", "unsupported_answer_rate")
    metric_table("False-abstain rate (lower is better; answerable questions the system refused)", "false_abstain_rate")
    metric_table("Contradiction-detection accuracy (flag genuine conflicts, do not flag version updates)", "contradiction_detection_accuracy")
    metric_table("Evidence coverage (a relevant source appears in the returned evidence)", "evidence_coverage")
    metric_table("Recall@5", "recall_at_5")
    metric_table("Precision@5", "precision_at_5")
    metric_table("MRR", "mrr")
    metric_table("nDCG@5", "ndcg_at_5")
    metric_table("Citation exactness (top evidence is the right note AND its excerpt contains the answer)", "citation_exact_top1")

    L.append("## Accuracy breakdown by case (temporal, phrasing, normalization, negation, chains)\n")
    rows = []
    for sc in ("temporal_reasoning", "historical_reconstruction", "memory_update_correction", "paraphrase_robustness", "value_normalization", "negation_and_correction", "evidence_fusion"):
        if sc not in scen:
            continue
        tags = sorted({t for s in systems for t in m[s]["scenarios"][sc].get("accuracy_by_tag", {})})
        for t in tags:
            rows.append([f"{sc} / {t}"] + [_pct(m[s]["scenarios"][sc].get("accuracy_by_tag", {}).get(t)) for s in systems])
    L.append(_table(["Case"] + systems, rows))
    L.append("")

    L.append("## Memory degradation after repeated updates\n")
    deg = rep["degradation_curve"]
    tags = sorted({t for s in systems for t in deg.get(s, {})}, key=lambda t: int(t.split("_")[1]))
    L.append(_table(["Updates applied"] + systems, [[t.replace("after_", "").replace("_updates", "")] + [_pct(deg.get(s, {}).get(t)) for s in systems] for t in tags]))
    L.append("")

    L.append("## Cost, latency and storage\n")
    rows = []
    for s in systems:
        sm = m[s]["scenarios"]
        tok = sum(v["mean_context_tokens"] for v in sm.values()) / len(sm)
        p50 = sorted(v["latency_ms_p50"] for v in sm.values())[len(sm) // 2]
        p95 = max(v["latency_ms_p95"] for v in sm.values())
        upd = sum(v["ingest_ms_per_event"] for v in sm.values()) / len(sm)
        sto = sum(v["storage_overhead_ratio"] for v in sm.values()) / len(sm)
        rows.append([s, f"{tok:.1f}", f"{p50:.2f}", f"{p95:.2f}", f"{upd:.2f}", f"{sto:.1f}×"])
    L.append(_table(["System", "Mean context tokens / question", "Query latency p50 (ms, median of scenarios)", "Query latency worst p95 (ms)", "Update cost (ms / event)", "Storage ÷ raw text"], rows))
    L.append("\nContext tokens are an estimate (≈4 characters per token) of the evidence each system returns for a reader to consume. Storage includes indexes, vectors, facts, version history and audit log for MemoraOS and vectors plus text for baselines.\n")

    L.append("## Persistence and consolidation\n")
    rows = []
    for s in systems:
        if "persistence_after_restart" not in m[s]["scenarios"] or "memory_consolidation" not in m[s]["scenarios"]:
            continue
        p = m[s]["scenarios"]["persistence_after_restart"]
        c = m[s]["scenarios"]["memory_consolidation"]
        rows.append([s, _pct(p.get("accuracy_before")), _pct(p["accuracy"]), f"{p.get('restart_seconds', 0):.3f}", _pct(c.get("accuracy_before")), _pct(c["accuracy"]), _pct(c.get("originals_intact")), f"{c.get('originals_modified', 0):.0f}" if "originals_modified" in c else "n/a"])
    L.append(_table(["System", "Accuracy before restart", "after restart", "Restart time (s)", "Consolidation: accuracy before", "after", "Originals intact", "Originals modified"], rows))
    L.append("\nIn-memory baselines must rebuild their index from raw documents after a restart (they are given the raw documents); MemoraOS reopens its SQLite file.\n")

    L.append("## External systems\n")
    L.append("These systems were **not executed**. No numbers are reported for them, and none are estimated.\n")
    L.append(_table(["System", "Executed", "Why not", "Needs"], [[e["system"], "no", e["reason"], e["requirement"]] for e in rep["external_systems"]]))
    L.append("")
    L.append("## How to read these results (limitations)\n")
    L.append("""- The datasets are **synthetic and authored by the MemoraOS project** to exercise specific capabilities (temporal facts, conflicts, multi-hop chains, abstention). Gains on them show that a mechanism works as designed; they do **not** predict performance on LoCoMo, LongMemEval or real conversations.
- Baselines are deliberately simple classical RAG pipelines built from the same tokenizer, embedder and reader as MemoraOS. They are not Mem0, Graphiti, Hindsight or Memorilla.
- Facts use templated English that MemoraOS's rule-based extractor is designed to parse. Free-form, paraphrased or implicit facts are not covered here; expect lower fact-engine coverage on them.
- `hybrid_rag_gated` gives the baseline the same abstention rule as MemoraOS so differences are not only due to refusing to answer. `memoraos_hybrid_only` forces MemoraOS to plain hybrid retrieval, isolating the contribution of routing and the truth engine.
- The hashing embedder is lexical. Semantic (paraphrase) recall with a neural embedder is not measured here.
- Scores are mechanical: an answer is correct when it contains every gold value and no stale/wrong value. Reader quality is held constant across systems.
""")
    return "\n".join(L)
