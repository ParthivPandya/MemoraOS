"""Scaling measurement for the vector index: exact brute force vs the opt-in IVF index.

Recall is measured on REAL text: sentences from this repository's docs plus Python's own reference prose
(pydoc topics, shipped with the interpreter), embedded with the default hashing embedder. Latency above the size of
that corpus is measured on random unit vectors and is labelled as latency-only; it says nothing about recall.

    python -m benchmarks.scaling
"""

from __future__ import annotations

import json
import re
import time
from pathlib import Path

import numpy as np

from memoraos.providers.local import HashingEmbedder, split_sentences
from memoraos.retrieval.ann import IVFIndex

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "benchmarks" / "reports"


def real_sentences() -> list[str]:
    texts = [p.read_text(encoding="utf-8", errors="replace") for p in sorted((ROOT / "docs").rglob("*.md"))]
    try:
        from pydoc_data import topics

        texts += list(topics.topics.values())
    except ImportError:
        pass
    seen, out = set(), []
    for t in texts:
        for s in split_sentences(re.sub(r"[`*#|>]+", " ", t)):
            s = " ".join(s.split())
            if 40 <= len(s) <= 400 and s not in seen:
                seen.add(s)
                out.append(s)
    return out


def timed(fn, reps: int) -> float:
    best = []
    for _ in range(reps):
        t = time.perf_counter()
        fn()
        best.append((time.perf_counter() - t) * 1000)
    return float(np.median(best))


def main() -> None:
    emb = HashingEmbedder(512)
    sents = real_sentences()
    rng = np.random.default_rng(7)
    order = rng.permutation(len(sents))
    qn = 200
    queries_txt = [sents[i] for i in order[:qn]]
    corpus_txt = [sents[i] for i in order[qn:]]
    t0 = time.perf_counter()
    mat_all = np.asarray(emb.embed(corpus_txt), dtype=np.float32)
    q = np.asarray(emb.embed(queries_txt), dtype=np.float32)
    embed_s = time.perf_counter() - t0
    rows = []
    for n in sorted({1000, 5000, 20000, len(corpus_txt)}):
        if n > len(corpus_txt):
            continue
        mat = mat_all[:n]
        nlist = int(np.sqrt(n) * 2)
        for nprobe in (4, 8, 16, 32):
            idx = IVFIndex(mat, nlist=nlist, nprobe=nprobe)
            hit = scored = 0
            for v in q:
                exact = set(np.argsort(-(mat @ v), kind="stable")[:10].tolist())
                approx, _ = idx.search(v, 10)
                hit += len(exact & set(approx.tolist()))
                probe = np.argsort(-(idx.centroids @ v))[:nprobe]
                scored += sum(len(idx.lists[i]) for i in probe)
            exact_ms = timed(lambda m=mat, v=q[0]: np.argsort(-(m @ v))[:10], 30)
            ivf_ms = timed(lambda i=idx, v=q[0]: i.search(v, 10), 30)
            rows.append({
                "vectors": n, "nlist": nlist, "nprobe": nprobe, "recall_at_10": round(hit / (10 * len(q)), 4),
                "scored_fraction": round(scored / (len(q) * n), 4), "exact_ms": round(exact_ms, 3), "ivf_ms": round(ivf_ms, 3),
            })
    rnd = []
    for n in (20000, 100000, 500000):
        m = rng.standard_normal((n, 512)).astype(np.float32)
        m /= np.linalg.norm(m, axis=1, keepdims=True)
        v = m[0]
        rnd.append({"vectors": n, "exact_ms": round(timed(lambda m=m, v=v: np.argsort(-(m @ v))[:10], 7), 2), "matrix_mb": round(m.nbytes / 1e6, 1)})
        del m
    res = {
        "corpus_sentences": len(corpus_txt), "queries": len(q), "embedder": emb.name, "embed_seconds": round(embed_s, 1),
        "real_text_recall": rows, "random_vectors_latency_only": rnd,
        "note": "recall rows use real sentences; random-vector rows measure brute-force latency only (no recall claim)",
    }
    OUT.mkdir(parents=True, exist_ok=True)
    (OUT / "scaling.json").write_text(json.dumps(res, indent=2), encoding="utf-8")
    lines = ["# Vector index scaling", "", "Generated by `python -m benchmarks.scaling`. Do not edit.", "",
             f"Real text: {len(corpus_txt):,} sentences from this repo's docs and Python's pydoc topics, {len(q)} held-out query sentences, hashing embedder (512 dims).", "",
             "## IVF recall against exact search (real text)", "", "| vectors | nlist | nprobe | recall@10 | scored | exact ms | ivf ms |", "|---:|---:|---:|---:|---:|---:|---:|"]
    lines += [f"| {r['vectors']:,} | {r['nlist']} | {r['nprobe']} | {r['recall_at_10']:.3f} | {r['scored_fraction']:.1%} | {r['exact_ms']} | {r['ivf_ms']} |" for r in rows]
    lines += ["", "## Exact brute-force latency at larger sizes (random unit vectors, latency only)", "", "| vectors | exact ms (median) | matrix MB |", "|---:|---:|---:|"]
    lines += [f"| {r['vectors']:,} | {r['exact_ms']} | {r['matrix_mb']} |" for r in rnd]
    (OUT / "SCALING.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
